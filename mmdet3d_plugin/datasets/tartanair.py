from scipy.spatial.transform import Rotation

"""
TartanAir Dataset Loader for Occupancy Prediction

Matches the output format of SemanticKITTIDataset for pipeline compatibility.

Coordinate Systems:
-------------------
TartanAir depth images are in Camera frame: X-right, Y-down, Z-forward

Voxel labels (generated by generate_voxels_robust.py with output_frame='lidar'):
- X: forward
- Y: left  
- Z: up
This matches SemanticKITTI LiDAR frame for model compatibility.

The T_velo_2_cam matrix transforms points from LiDAR-like frame to camera frame:
    P_cam = T_velo_2_cam @ P_lidar
"""

# TartanAir camera intrinsics (pinhole model)
TARTANAIR_FOCAL_LENGTH = 320.0
TARTANAIR_CX = 320.0
TARTANAIR_CY = 320.0
TARTANAIR_IMG_WIDTH = 640
TARTANAIR_IMG_HEIGHT = 640

# Transformation from LiDAR-like frame to Camera frame
# LiDAR: X-forward, Y-left, Z-up
# Camera: X-right, Y-down, Z-forward
#
# X_cam = -Y_lidar (right = -left)
# Y_cam = -Z_lidar (down = -up)  
# Z_cam = X_lidar  (forward = forward)
LIDAR_TO_CAM = np.array([
    [0, -1,  0, 0],   # X_cam = -Y_lidar
    [0,  0, -1, 0],   # Y_cam = -Z_lidar
    [1,  0,  0, 0],   # Z_cam = X_lidar
    [0,  0,  0, 1],
], dtype=np.float32)


def parse_pose_string(pose_str):
    """
    Parse TartanAir pose string "x y z qx qy qz qw" to 4x4 matrix.
    
    Args:
        pose_str: String "x y z qx qy qz qw" (position + quaternion in NED frame)
    
    Returns:
        4x4 transformation matrix (world_T_camera in NED frame)
    """
    values = [float(v) for v in pose_str.strip().split()]
    
    if len(values) != 7:
        raise ValueError(f"Expected 7 values (x y z qx qy qz qw), got {len(values)}")
    
    x, y, z, qx, qy, qz, qw = values
    position = np.array([x, y, z])
    quaternion = np.array([qx, qy, qz, qw])
    
    # Convert quaternion to rotation matrix
    rotation = Rotation.from_quat(quaternion)  # scipy uses [x, y, z, w]
    
    # Build 4x4 transformation matrix
    pose = np.eye(4)
    pose[:3, :3] = rotation.as_matrix()
    pose[:3, 3] = position
    
    return pose


def load_poses_from_file(pose_file):
    """
    Load poses from TartanAir pose file.
    
    Args:
        pose_file: Path to pose file
    
    Returns:
        List of 4x4 transformation matrices (in NED frame)
    """
    poses = []
    with open(pose_file, "r") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                pose = parse_pose_string(line)
                poses.append(pose)
    return poses


def get_tartanair_intrinsic_matrix():
    """
    Get TartanAir camera intrinsic matrix (4x4 for KITTI format compatibility).
    
    Returns:
        4x4 intrinsic matrix matching KITTI P2/P3 format
    """
    K = np.eye(4, dtype=np.float32)
    K[0, 0] = TARTANAIR_FOCAL_LENGTH  # fx
    K[1, 1] = TARTANAIR_FOCAL_LENGTH  # fy
    K[0, 2] = TARTANAIR_CX            # cx
    K[1, 2] = TARTANAIR_CY            # cy
    return K


@DATASETS.register_module()
class TartanAirDataset(Dataset):
    """
    TartanAir Dataset for Occupancy Prediction.
    
    Matches the output format of SemanticKITTIDataset for use with the same
    data pipeline and model architecture.
    
    Directory structure expected:
        data_root/
        ├── {env_name}/
        │   └── {difficulty}/
        │       └── P{trajectory_id}/
        │           ├── image_{camera}/
        │           │   └── {frame_id}_{camera}.png
        │           ├── depth_{camera}/
        │           │   └── {frame_id}_{camera}_depth.png
        │           ├── seg_{camera}/
        │           │   └── {frame_id}_{camera}_seg.png
        │           ├── pose_{camera}.txt
        │           └── voxel_label_{camera}/
        │               └── {frame_id}_voxel_label.npy
    
    Args:
        data_root: Root directory of dataset
        ann_file: Path to voxel labels directory
        depth_root: Path to depth directory (if different from data_root)
        pipeline: Data pipeline
        split: 'train', 'val', or 'test'
        camera_used: List of camera names ['front'] 
        occ_size: Voxel grid dimensions [X, Y, Z]
        pc_range: Point cloud range [x_min, y_min, z_min, x_max, y_max, z_max]
        test_mode: Whether in test mode
        load_continuous: Load all frames (not just those with voxel labels)
        sequences: List of sequence identifiers (env/difficulty/trajectory)
    """
    
    def __init__(
        self,
        data_root,
        ann_file,
        depth_root,
        pipeline,
        split,
        camera_used,
        occ_size,
        pc_range,
        test_mode=False,
        load_continuous=False,
        sequences=None,
    ):
        super().__init__()
        
        self.data_root = data_root
        self.ann_file = ann_file
        self.depth_root = depth_root if depth_root else data_root
        self.test_mode = test_mode
        self.load_continuous = load_continuous
        
        self.occ_size = occ_size
        self.pc_range = pc_range
        
        # Camera mapping - TartanAir camera names to internal IDs
        # For compatibility with KITTI-style pipeline, we use '2' as the main camera
        self.camera_map = {
            'front': 'lcam_front',
            'back': 'lcam_back',
            'left': 'lcam_left',
            'right': 'lcam_right',
            'fish': 'lcam_fish',
            'equirect': 'lcam_equirect',
        }
        
        # Handle camera_used - convert to TartanAir format
        if isinstance(camera_used, str):
            camera_used = [camera_used]
        self.camera_used = []
        for cam in camera_used:
            if cam in self.camera_map:
                self.camera_used.append(self.camera_map[cam])
            else:
                self.camera_used.append(cam)  # Use as-is
        
        # Debug output
        print(f"TartanAirDataset initialization:")
        print(f"  data_root: {self.data_root}")
        print(f"  ann_file: {self.ann_file}")
        print(f"  depth_root: {self.depth_root}")
        print(f"  camera_used: {self.camera_used}")
        print(f"  split: {split}")
        print(f"  sequences provided: {sequences is not None}")
        
        # Define sequences for each split
        if sequences is not None:
            self.sequences = sequences
            print(f"  Using provided sequences: {self.sequences}")
        else:
            self.sequences = self._get_default_sequences(split)
        
        # Load annotations
        self.data_infos = self.load_annotations()
        
        if pipeline is not None:
            self.pipeline = Compose(pipeline)
        
        self._set_group_flag()
    
    def _get_default_sequences(self, split):
        """
        Get default sequence list for a split.
        
        Override this method or pass sequences parameter to customize.
        
        Returns list of tuples: (env_name, difficulty, trajectory_id)
        """
        # Discover available sequences
        sequences = []
        
        print(f"Auto-discovering sequences in: {self.data_root}")
        print(f"Looking for camera: {self.camera_used}")
        
        for env_name in sorted(os.listdir(self.data_root)):
            env_path = os.path.join(self.data_root, env_name)
            if not os.path.isdir(env_path) or env_name.startswith('.'):
                continue
            
            for difficulty in ['Data_easy', 'Data_hard']:
                diff_path = os.path.join(env_path, difficulty)
                if not os.path.exists(diff_path):
                    continue
                
                for traj in sorted(os.listdir(diff_path)):
                    traj_path = os.path.join(diff_path, traj)
                    if not (traj.startswith('P') and os.path.isdir(traj_path)):
                        continue
                    
                    # Check if voxel labels exist for at least one camera
                    has_voxels = False
                    for camera in self.camera_used:
                        voxel_dir = os.path.join(traj_path, f'voxel_label_{camera}')
                        if os.path.exists(voxel_dir):
                            voxel_files = glob.glob(os.path.join(voxel_dir, '*_voxel_label.npy'))
                            if len(voxel_files) > 0:
                                has_voxels = True
                                print(f"  Found: {env_name}/{difficulty}/{traj} ({len(voxel_files)} voxel files)")
                                break
                    
                    if has_voxels:
                        sequences.append((env_name, difficulty, traj))
        
        if not sequences:
            # Fallback: try to find sequences directly under data_root
            print(f"No sequences found with standard structure, trying flat structure...")
            for item in sorted(os.listdir(self.data_root)):
                item_path = os.path.join(self.data_root, item)
                if os.path.isdir(item_path) and item.startswith('P'):
                    for camera in self.camera_used:
                        voxel_dir = os.path.join(item_path, f'voxel_label_{camera}')
                        if os.path.exists(voxel_dir):
                            voxel_files = glob.glob(os.path.join(voxel_dir, '*_voxel_label.npy'))
                            if len(voxel_files) > 0:
                                sequences.append(('', '', item))
                                print(f"  Found: {item} ({len(voxel_files)} voxel files)")
                                break
        
        print(f"Total sequences discovered: {len(sequences)}")
        
        if len(sequences) == 0:
            print("WARNING: No sequences found! Check your data_root and voxel generation.")
            return []
        
        # Split sequences (80% train, 20% val/test)
        # Ensure at least 1 sequence for val/test if we have multiple
        n_train = max(1, int(len(sequences) * 0.8))
        if len(sequences) > 1:
            n_train = min(n_train, len(sequences) - 1)  # Leave at least 1 for val
        
        if split == 'train':
            selected = sequences[:n_train]
        else:  # val or test
            selected = sequences[n_train:] if n_train < len(sequences) else sequences
        
        print(f"Split '{split}': {len(selected)} sequences")
        return selected
    
    def __len__(self):
        return len(self.data_infos)
    
    def _set_group_flag(self):
        """Set flag according to image aspect ratio."""
        self.flag = np.zeros(len(self), dtype=np.uint8)
    
    def _rand_another(self, idx):
        """Randomly get another item with the same flag."""
        pool = np.where(self.flag == self.flag[idx])[0]
        return np.random.choice(pool)
    
    def prepare_train_data(self, index):
        """Training data preparation."""
        input_dict = self.get_data_info(index)
        if input_dict is None:
            print('found None in training data')
            return None
        
        example = self.pipeline(input_dict)
        return example
    
    def prepare_test_data(self, index):
        """Test data preparation."""
        input_dict = self.get_data_info(index)
        if input_dict is None:
            print('found None in test data')
            return None
        
        example = self.pipeline(input_dict)
        return example
    
    def __getitem__(self, idx):
        if self.test_mode:
            return self.prepare_test_data(idx)
        while True:
            data = self.prepare_train_data(idx)
            if data is None:
                idx = self._rand_another(idx)
                continue
            return data
    
    def load_annotations(self):
        """
        Load all scan information from the dataset.
        
        Returns:
            List of dictionaries containing scan info (matching KITTI format)
        """
        scans = []
        
        print(f"Loading annotations from {len(self.sequences)} sequences...")
        
        for seq_info in self.sequences:
            if isinstance(seq_info, tuple) and len(seq_info) == 3:
                env_name, difficulty, traj_id = seq_info
                traj_dir = os.path.join(self.data_root, env_name, difficulty, traj_id)
                sequence_name = f"{env_name}_{difficulty}_{traj_id}"
            else:
                # Single path format
                traj_dir = os.path.join(self.data_root, seq_info)
                sequence_name = seq_info
                env_name, difficulty, traj_id = '', '', seq_info
            
            if not os.path.exists(traj_dir):
                print(f"  WARNING: Trajectory directory not found: {traj_dir}")
                continue
            
            # Process each camera
            for camera in self.camera_used:
                camera_scans = self._load_camera_scans(
                    traj_dir, camera, sequence_name, env_name, difficulty, traj_id
                )
                if len(camera_scans) > 0:
                    print(f"  {sequence_name}/{camera}: {len(camera_scans)} frames")
                scans.extend(camera_scans)
        
        print(f"Loaded {len(scans)} samples from TartanAir")
        return scans
    
    def _load_camera_scans(self, traj_dir, camera, sequence_name, env_name, difficulty, traj_id):
        """Load scans for a specific camera in a trajectory."""
        scans = []
        
        # Paths
        img_dir = os.path.join(traj_dir, f'image_{camera}')
        depth_dir = os.path.join(self.depth_root, env_name, difficulty, traj_id, f'depth_{camera}') \
                    if env_name else os.path.join(self.depth_root, traj_id, f'depth_{camera}')
        voxel_dir = os.path.join(self.ann_file, env_name, difficulty, traj_id, f'voxel_label_{camera}') \
                    if env_name else os.path.join(self.ann_file, traj_id, f'voxel_label_{camera}')
        pose_file = os.path.join(traj_dir, f'pose_{camera}.txt')
        
        # Check directories exist
        if not os.path.exists(img_dir):
            print(f"    WARNING: Image dir not found: {img_dir}")
            return scans
        
        if not os.path.exists(voxel_dir):
            print(f"    WARNING: Voxel dir not found: {voxel_dir}")
            # If load_continuous, we can still load without voxels
            if not self.load_continuous:
                return scans
        
        # Load poses
        poses = []
        if os.path.exists(pose_file):
            poses = load_poses_from_file(pose_file)
        
        # Get intrinsic matrix (4x4 for KITTI compatibility)
        P = get_tartanair_intrinsic_matrix()
        
        # T_velo_2_cam transforms from LiDAR-like frame to camera frame
        # This is needed because voxels are generated in LiDAR-like frame
        # (when using output_frame='lidar' in generate_voxels_robust.py)
        #
        # LiDAR frame: X-forward, Y-left, Z-up
        # Camera frame: X-right, Y-down, Z-forward
        T_velo_2_cam = LIDAR_TO_CAM.copy()
        
        # Projection matrix: P @ T_velo_2_cam
        proj_matrix = P @ T_velo_2_cam
        
        # Find frames
        if self.load_continuous:
            frame_pattern = os.path.join(img_dir, '*.png')
        else:
            frame_pattern = os.path.join(voxel_dir, '*_voxel_label.npy')
        
        frame_files = sorted(glob.glob(frame_pattern))
        
        for frame_file in frame_files:
            filename = os.path.basename(frame_file)
            
            if self.load_continuous:
                # Extract frame_id from: 000000_lcam_front.png
                frame_id = filename.split('_')[0]
            else:
                # Extract frame_id from: 000000_voxel_label.npy
                frame_id = filename.replace('_voxel_label.npy', '')
            
            # Build paths
            img_path = os.path.join(img_dir, f'{frame_id}_{camera}.png')
            depth_path = os.path.join(depth_dir, f'{frame_id}_{camera}_depth.png')
            voxel_path = os.path.join(voxel_dir, f'{frame_id}_voxel_label.npy')
            
            # Skip if image doesn't exist
            if not os.path.exists(img_path):
                continue
            
            # Check voxel file
            if not os.path.exists(voxel_path):
                voxel_path = None
            
            # Check depth file
            if not os.path.exists(depth_path):
                depth_path = None
            
            # Create scan info matching KITTI format
            # We use 'img_2_path' naming for compatibility with pipeline
            scan = {
                "img_2_path": img_path,
                "img_3_path": img_path,  # Same image (no stereo)
                "sequence": sequence_name,
                "frame_id": frame_id,
                "P2": P.copy(),
                "P3": P.copy(),  # Same intrinsics (no stereo)
                "T_velo_2_cam": T_velo_2_cam.copy(),
                "proj_matrix_2": proj_matrix.copy(),
                "proj_matrix_3": proj_matrix.copy(),
                "voxel_path": voxel_path,
                "stereo_depth_path": depth_path,  # Use TartanAir depth
                "depth_path": depth_path,
                "camera": camera,
            }
            
            scans.append(scan)
        
        return scans
    
    def get_data_info(self, index):
        """
        Get data info for a specific index.
        
        Returns a dictionary matching SemanticKITTI format exactly.
        """
        info = self.data_infos[index]
        
        input_dict = dict(
            occ_size=np.array(self.occ_size),
            pc_range=np.array(self.pc_range),
            sequence=info['sequence'],
            frame_id=info['frame_id'],
        )
        
        # Load images, intrins, extrins matching KITTI format
        image_paths = []
        lidar2cam_rts = []
        lidar2img_rts = []
        cam_intrinsics = []
        
        # TartanAir uses single camera, but we format like KITTI
        # camera_used would be ['2'] in KITTI, here we just use one camera
        image_paths.append(info['img_2_path'])
        lidar2img_rts.append(info['proj_matrix_2'])
        cam_intrinsics.append(info['P2'])
        lidar2cam_rts.append(info['T_velo_2_cam'])
        
        # Focal length from intrinsics
        focal_length = info['P2'][0, 0]
        
        # No stereo baseline for TartanAir (single camera)
        # Use a small non-zero value to avoid division issues
        baseline = 0.54  # Similar to KITTI baseline for compatibility
        
        input_dict.update(
            dict(
                img_filename=image_paths,
                lidar2img=lidar2img_rts,
                cam_intrinsic=cam_intrinsics,
                lidar2cam=lidar2cam_rts,
                focal_length=focal_length,
                baseline=baseline
            )
        )
        
        # Depth path (TartanAir has dense depth)
        input_dict['stereo_depth_path'] = info['stereo_depth_path']
        input_dict['depth_path'] = info['depth_path']
        
        # Ground truth occupancy
        input_dict['gt_occ'] = self.get_ann_info(index, key='voxel_path')
        
        return input_dict
    
    def get_ann_info(self, index, key='voxel_path'):
        """Load annotation (voxel occupancy) for a given index."""
        info = self.data_infos[index][key]
        if info is None:
            return None
        if not os.path.exists(info):
            return None
        return np.load(info)
    
